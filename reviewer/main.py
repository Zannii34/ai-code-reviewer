import fnmatch
import sys

from reviewer.config import load_config
from reviewer.github import get_pr_client, get_pr_diff, post_review_comment
from reviewer.ai import review_diff


def _path_is_ignored(path, config):
    """Return True when a changed file should be excluded from the review."""
    normalized = path.replace("\\", "/").lstrip("./")

    for pattern in config.get("ignore_files", []):
        if fnmatch.fnmatch(normalized, pattern) or fnmatch.fnmatch(
            normalized.split("/")[-1], pattern
        ):
            return True

    for pattern in config.get("ignore_patterns", []):
        normalized_pattern = pattern.replace("\\", "/").rstrip("*")
        if normalized_pattern and normalized_pattern in normalized:
            return True

    return False


def filter_diff(diff, config):
    """Remove ignored files from a unified Git diff and limit its size."""
    if not diff.strip():
        return ""

    lines = diff.splitlines()
    filtered = []
    current_file = None
    skip_current_file = False

    for line in lines:
        if line.startswith("diff --git "):
            parts = line.split()
            current_file = None

            if len(parts) >= 4:
                current_file = parts[3]
                if current_file.startswith("b/"):
                    current_file = current_file[2:]

            skip_current_file = bool(
                current_file and _path_is_ignored(current_file, config)
            )

        if not skip_current_file:
            filtered.append(line)

    max_lines = config.get("max_diff_lines", 500)

    if max_lines and len(filtered) > max_lines:
        filtered = filtered[:max_lines]
        filtered.append("... (diff truncated for review)")

    return "\n".join(filtered)


def main():
    print("[1/5] Loading config...")
    config = load_config()

    print("[2/5] Connecting to GitHub...")
    repo, pr = get_pr_client()
    print(f"PR #{pr.number}: {pr.title}")

    print("[3/5] Fetching diff...")
    diff = get_pr_diff(pr)

    if not diff.strip():
        print("No changes to review.")
        return

    diff = filter_diff(diff, config)

    if not diff.strip():
        print("No reviewable changes after applying ignore rules.")
        return

    print(f"Diff size: {len(diff.splitlines())} lines")

    print("[4/5] Sending diff to Claude...")
    review = review_diff(
        diff=diff,
        pr_title=pr.title,
        pr_body=pr.body or "",
        model=config.get("model"),
    )

    print("[5/5] Posting review comment...")
    body = (
        "## AI Code Review\n\n"
        + review
        + "\n\n---\n"
        "*Generated by ai-code-reviewer*"
    )
    post_review_comment(pr, body)

    print("Done.")


if __name__ == "__main__":
    try:
        main()
    except Exception as e:
        print(f"[ERROR] {e}", file=sys.stderr)
        sys.exit(1)
